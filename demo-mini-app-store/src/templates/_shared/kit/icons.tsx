/** Render icon theo mã ZaUI (`zi-*`), có hỗ trợ trạng thái `active` (filled). */
export function ZmpIcon({
  name = "",
  size = 20,
  active = false,
  className = "",
}: {
  name?: string;
  size?: number;
  active?: boolean;
  className?: string;
}) {
  const entry = ZMP_ICON_MAP[name];
  if (!entry) return <LuSparkles size={size} className={className} />;
  const Comp = active ? entry.filled : entry.outline;
  return <Comp size={size} className={className} />;
}

/**
 * Tự động chuyển đổi một chuỗi emoji (VD `"👗"`, `"☕"`, `"📅"`) hoặc mã `zi-*`
 * thành vector icon của `react-icons`. Nếu truyền vào một ReactElement thì giữ nguyên.
 */
export function SmartIcon({
  token,
  size = 22,
  className = "",
}: {
  token: ReactNode;
  size?: number;
  className?: string;
}) {
  if (typeof token === "string") {
    const trimmed = token.trim();
    if (trimmed.startsWith("zi-")) {
      return <ZmpIcon name={trimmed} size={size} className={className} />;
    }
    const Mapped = EMOJI_ICON_MAP[trimmed];
    if (Mapped) {
      return <Mapped size={size} className={className} />;
    }
    // Nếu là chuỗi 1-2 ký tự chữ cái (VD logo "L", "T", "re") thì giữ nguyên chữ
    if (/^[a-zA-Z0-9À-ỹ]{1,3}$/.test(trimmed)) {
      return <span className={className}>{trimmed}</span>;
    }
    return <LuSparkles size={size} className={className} />;
  }
  return <>{token}</>;
}
